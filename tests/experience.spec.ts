import { test, expect } from '@playwright/test';

test('boots into the 3D scene and opens the local desktop inside the monitor', async ({ page }) => {
  const errors: string[] = [];
  page.on('pageerror', e => errors.push(e.message));
  page.on('response', r => { if (r.status() >= 400) errors.push(`${r.status()} ${r.url()}`); });
  await page.goto('/');
  await expect(page.getByRole('button', { name: 'START', exact: true })).toBeVisible();
  // The BIOS dialog fades in only after all scene resources have loaded.
  await page.waitForTimeout(2500);
  await page.getByRole('button', { name: 'START', exact: true }).click();
  await expect(page.getByText('Click anywhere to begin', { exact: true })).toBeVisible({ timeout: 15000 });
  await page.waitForTimeout(3000);
  await page.screenshot({ path: 'test-results/scene.png' });
  await page.mouse.click(450, 700);
  await page.waitForTimeout(2200);
  await page.mouse.move(720, 430);
  await page.waitForTimeout(2500);
  const desktop = page.frameLocator('#computer-screen');
  await desktop.getByRole('button', { name: 'About Connor', exact: true }).first().click();
  await expect(desktop.getByRole('dialog', { name: 'About Connor' })).toBeVisible();
  await expect(desktop.locator('.portrait')).toHaveJSProperty('complete', true);
  await page.mouse.move(730, 450);
  await page.waitForTimeout(500);
  await page.screenshot({ path: 'test-results/monitor.png' });
  expect(errors).toEqual([]);
});

test('desktop apps, window controls, personalization and keyboard unlocking work', async ({ page }) => {
  await page.goto('/desktop.html');
  await page.getByRole('button', { name: 'About Connor', exact: true }).first().click();
  const about = page.getByRole('dialog', { name: 'About Connor' });
  await expect(about.getByRole('heading', { name: /my name is Connor Love/ })).toBeVisible();
  await about.getByRole('button', { name: 'Projects', exact: true }).click();
  await expect(about.locator('.projects a')).toHaveCount(3);
  await expect(about.locator('.projects a').first()).toHaveAttribute('href', 'https://www.connorlove.com/projects/honestui');
  await page.getByLabel('Minimize about', { exact: true }).click();
  await expect(about).toHaveCount(0);
  await page.getByRole('button', { name: 'About Connor', exact: true }).first().click();
  await expect(about).toBeVisible();
  await page.getByLabel('Maximize about', { exact: true }).click();
  await expect(about).toHaveClass(/maximized/);
  await page.getByLabel('Maximize about', { exact: true }).click();
  const before = await about.boundingBox();
  await page.mouse.move(before!.x + 200, before!.y + 16);
  await page.mouse.down();
  await page.mouse.move(before!.x + 250, before!.y + 66, { steps: 5 });
  await page.mouse.up();
  const after = await about.boundingBox();
  expect(after!.x).toBeGreaterThan(before!.x);
  await page.getByRole('button', { name: 'Terminal', exact: true }).click();
  await page.getByLabel('Terminal command').fill('whoami');
  await page.getByLabel('Terminal command').press('Enter');
  await expect(page.locator('.terminal pre').last()).toContainText('Connor Love');
  await page.getByRole('button', { name: 'Calculator', exact: true }).click();
  for (const key of ['7', '×', '6', '=']) await page.locator('.calc-keys').getByRole('button', { name: key, exact: true }).click();
  await expect(page.locator('output')).toHaveText('42');
  await page.getByRole('button', { name: 'Settings', exact: true }).click();
  await page.getByRole('button', { name: 'forest wallpaper' }).click();
  await expect(page.locator('.desktop')).toHaveClass('desktop forest');
  await page.getByRole('button', { name: 'Lock screen', exact: true }).click();
  await expect(page.locator('.lock-screen')).toBeVisible();
  await page.keyboard.press('Enter');
  await expect(page.locator('.lock-screen')).toHaveCount(0);
  await page.getByLabel('Close settings', { exact: true }).click();
  await page.getByLabel('Close calculator', { exact: true }).click();
  await page.getByLabel('Close terminal', { exact: true }).click();
  await about.getByRole('button', { name: 'Contact', exact: true }).click();
  await expect(page.getByLabel('To', { exact: true })).toHaveValue('loveconnor2005@gmail.com');
  await page.reload();
  await expect(page.locator('.desktop')).toHaveClass('desktop forest');
  await page.getByRole('button', { name: 'Launchpad', exact: true }).click();
  await page.getByLabel('Search applications').fill('Terminal');
  await expect(page.locator('.application-grid button')).toHaveCount(1);
});

