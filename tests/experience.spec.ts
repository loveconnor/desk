test('Notes organizes projects, social links, and the actual résumé', async ({ page }) => {
  await page.goto('/desktop.html');
  await expect(page.locator('.document-shortcuts')).toHaveCount(0);
  await page.getByRole('button', {name: 'Notes', exact: true}).click();
  const notes = page.getByRole('dialog', {name:'Notes',exact:true});
  await notes.getByRole('button', {name:/Social links Find me/}).click();
  await expect(notes.getByRole('link',{name:'GitHub'})).toHaveAttribute('href','https://github.com/loveconnor');
  await notes.getByRole('button',{name:/Projects HonestUI/}).click();
  await notes.getByRole('button',{name:'HonestUI Design & development',exact:true}).click();
  await expect(notes.getByRole('link',{name:'View HonestUI'})).toBeVisible();
  await notes.getByRole('textbox',{name:'Search notes'}).fill('Résumé');
  await expect(notes.getByRole('heading',{name:'Résumé',exact:true})).toBeVisible();
  await notes.getByRole('button',{name:/Résumé.pdf/}).click();
  const reader=page.getByRole('dialog',{name:'Connor Love résumé',exact:true});
  await expect(reader).toBeVisible();
  await expect(reader.locator('.held-paper img')).toHaveAttribute('src','/resume/preview.png');
  await expect(reader.locator('iframe')).toHaveCount(0);
  await reader.getByRole('button',{name:'Zoom in',exact:true}).click();
  await expect(reader).toHaveClass(/zoomed/);
  const pdf=await page.request.get('/resume/resume.pdf');
  expect(pdf.ok()).toBeTruthy();
  expect((await pdf.body()).subarray(0,5).toString()).toBe('%PDF-');
  await reader.getByRole('button',{name:'Close document'}).click();
  await expect(reader).toHaveCount(0);
  await notes.getByRole('textbox',{name:'Search notes'}).fill('not-a-note');
  await expect(notes.getByRole('heading',{name:'No notes found'})).toBeVisible();
});

test('Music shows the curated work playlist and selects previews', async ({ page }) => {
  await page.goto('/desktop.html');
  await page.getByRole('button', {name:'Music',exact:true}).click();
  const music=page.getByRole('dialog',{name:'Music',exact:true});
  await expect(music.getByRole('heading',{name:'Quiet Hours'})).toBeVisible();
  await expect(music.locator('.music-track')).toHaveCount(40);
  await expect(music.locator('.playlist-photo')).toHaveJSProperty('naturalWidth', 1254);
  const artists=await music.locator('.track-meta small').allTextContents();
  expect(new Set(artists).size).toBeGreaterThanOrEqual(20);
  expect(artists).toEqual(expect.arrayContaining(['Ricci Paolo','Newport','Shaboozey','Coldplay']));
  expect(artists.some(a=>/Harry Styles|Ed Sheeran|James Bay|Shawn Mendes|Jenna Raine|Livingston|Benson Boone|Josiah Queen|Julia Poe/.test(a))).toBe(false);
  await music.getByRole('button',{name:'Preview These Are The Days by Mark Ambor',exact:true}).click();
  await expect(music.locator('audio')).toHaveAttribute('src',/^https:\/\//);
  await expect(music.locator('.now-playing')).toContainText('These Are The Days');
  await expect(music.getByRole('link',{name:'Open These Are The Days in Apple Music',exact:true})).toHaveAttribute('href',/^https:\/\/music.apple.com\//);
});
